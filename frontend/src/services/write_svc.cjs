const fs = require('fs');
const lines = [];
lines.push("// projectsDbService.ts - Project DB persistence service");
lines.push("import { supabase } from './supabaseClient';");
lines.push("import type { Project } from '../types/project';");
lines.push("");
lines.push("const MAX_ROWS = 300;");
lines.push("");
lines.push("function toDbRow(p: Project, isActive: boolean) {");
lines.push("  const ds = { ...p.dataSource, rawRows: (p.dataSource?.rawRows||[]).slice(0,MAX_ROWS) };");
lines.push("  return {");
lines.push("    id: p.id, title: p.title||'مشروع', description: p.description||null,");
lines.push("    category: p.category||'sales', icon: p.icon||'📊',");
lines.push("    color_accent: p.colorAccent||'sky', data_source_type: p.dataSourceType||'google_sheets',");
lines.push("    google_sheet_url: p.googleSheetUrl||null, is_public: p.isPublic??false,");
lines.push("    is_active: isActive, dashboard: p.dashboard as any, data_source: ds as any,");
lines.push("    database_config: (p.databaseConfig as any)||null,");
lines.push("    active_filters: p.activeFilters||{}, widget_filters: p.widgetFilters||{},");
lines.push("    drill_down_states: p.drillDownStates||{}, theme: p.theme||'dark',");
lines.push("    updated_at: new Date().toISOString()");
lines.push("  };");
lines.push("}");
lines.push("");
lines.push("function fromDbRow(r: any): Project {");
lines.push("  return {");
lines.push("    id: r.id, title: r.title, description: r.description||'',");
lines.push("    category: r.category||'sales', icon: r.icon||'📊',");
lines.push("    colorAccent: r.color_accent||'sky', createdAt: r.created_at, updatedAt: r.updated_at,");
lines.push("    dataSourceType: r.data_source_type||'google_sheets', googleSheetUrl: r.google_sheet_url||undefined,");
lines.push("    isPublic: r.is_public??false, databaseConfig: r.database_config||undefined,");
lines.push("    dashboard: r.dashboard, dataSource: r.data_source,");
lines.push("    activeFilters: r.active_filters||{}, widgetFilters: r.widget_filters||{},");
lines.push("    drillDownStates: r.drill_down_states||{}, theme: r.theme||'dark'");
lines.push("  };");
lines.push("}");
lines.push("");
lines.push("export interface SaveResult { success: boolean; error?: string; }");
lines.push("export interface LoadResult { success: boolean; projects?: Project[]; activeProjectId?: string; error?: string; }");
lines.push("");
lines.push("export async function saveAllProjectsToDb(projects: Project[], activeProjectId: string): Promise<SaveResult> {");
lines.push("  try {");
lines.push("    if (!projects||projects.length===0) return {success:true};");
lines.push("    const rows = projects.map(p=>toDbRow(p,p.id===activeProjectId));");
lines.push("    const {error} = await supabase.from('projects').upsert(rows,{onConflict:'id'});");
lines.push("    if (error){console.warn('[projectsDb] upsert:',error.message);return {success:false,error:error.message};}");
lines.push("    return {success:true};");
lines.push("  } catch(err: any){return {success:false,error:err?.message||'Save error'};}");
lines.push("}");
lines.push("");
lines.push("export async function saveProjectToDb(project: Project, isActive: boolean): Promise<SaveResult> {");
lines.push("  try {");
lines.push("    const {error} = await supabase.from('projects').upsert(toDbRow(project,isActive),{onConflict:'id'});");
lines.push("    if (error) return {success:false,error:error.message};");
lines.push("    return {success:true};");
lines.push("  } catch(err: any){return {success:false,error:err?.message||'Save error'};}");
lines.push("}");
lines.push("");
lines.push("export async function loadProjectsFromDb(): Promise<LoadResult> {");
lines.push("  try {");
lines.push("    const {data,error} = await supabase.from('projects').select('*').order('updated_at',{ascending:false});");
lines.push("    if (error){console.warn('[projectsDb] load:',error.message);return {success:false,error:error.message};}");
lines.push("    if (!data||data.length===0) return {success:true,projects:[],activeProjectId:undefined};");
lines.push("    const loaded = data.map(fromDbRow).filter((p: Project)=>Boolean(p.id&&p.dashboard&&p.dataSource));");
lines.push("    const ar = data.find((r: any)=>r.is_active===true);");
lines.push("    return {success:true,projects:loaded,activeProjectId:ar?.id||loaded[0]?.id};");
lines.push("  } catch(err: any){return {success:false,error:err?.message||'Load error'};}");
lines.push("}");
lines.push("");
lines.push("export async function deleteProjectFromDb(projectId: string): Promise<SaveResult> {");
lines.push("  try {");
lines.push("    const {error} = await supabase.from('projects').delete().eq('id',projectId);");
lines.push("    if (error) return {success:false,error:error.message};");
lines.push("    return {success:true};");
lines.push("  } catch(err: any){return {success:false,error:err?.message||'Delete error'};}");
lines.push("}");
lines.push("");
const content = lines.join('\n');
fs.writeFileSync('projectsDbService.ts', content, {encoding:'utf8'});
console.log('Written OK:', content.length, 'chars');
